#!/usr/bin/env python3
"""Worklist of untyped memory access in our source (the struct pass).

Lists every place in src/s3re that still reaches game memory by a raw
address or offset instead of a typed struct / typed global:

  rawat     RawAt<T>(object, offset): a field of an object whose layout
            isn't mapped (should become a packed struct field)
  global    a data address of S3.EXE (a hex literal in 0x63a000..0x7ed000:
            .rdata/.data globals, tables, strings, vtables) outside the
            headers that declare them (game/globals.h, tables.h, texts.h,
            vtables.h; should become one typed declaration there, recorded
            in re/globals.csv). typed_access_lint.py rejects new ones.
  code      a code address (< 0x63a000) used as a function pointer: calls of
            original functions and hook targets. Allowed (needed for Detours
            and the test stubs); counted only, not listed.

Usage:
  python tools/raw_access_report.py            # summary per file
  python tools/raw_access_report.py --write    # also writes re/typed_access_todo.md
  python tools/raw_access_report.py --list     # every finding

Lines marked `raw-ok` are reported separately (justified exceptions).
"""

import argparse
import collections
import csv
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "src" / "s3re"
SKIP = {"game/raw.h", "game/global_access.h", "game/globals.h", "game/tables.h", "game/texts.h", "game/vtables.h"}
CODE_END = 0x63A000

ADDRESS = re.compile(r"0x0*([0-9a-fA-F]{6})\b")
ADDRESS_USE = re.compile(
    r"(RawAtAddress<|GameGlobal<|reinterpret_cast<[^;]*?>\s*\(\s*|constexpr\s+(?:std::)?uintptr_t\s+\w+\s*=\s*)"
    r"0x0*([0-9a-fA-F]{6})\b")
RAWAT = re.compile(r"(?<!\w)RawAt<")


def load_globals():
    names = {}
    path = ROOT / "re" / "globals.csv"
    with path.open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            names[int(row["address"], 16)] = row["name"]
    return names


def scan():
    found = []  # (kind, file, line, address or None, text)
    code_refs = 0
    for path in sorted(SOURCES.rglob("*")):
        if path.suffix not in (".cpp", ".h"):
            continue
        rel = path.relative_to(SOURCES).as_posix()
        if rel in SKIP:
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            code = line.split("//", 1)[0]
            ok = "raw-ok" in line
            if RAWAT.search(code):
                found.append(("rawat", rel, number, None, line.strip(), ok))
            for m in ADDRESS_USE.finditer(code):
                value = int(m.group(2), 16)
                if 0x400000 <= value < CODE_END:
                    code_refs += 1
            for m in ADDRESS.finditer(code):
                value = int(m.group(1), 16)
                if CODE_END <= value < 0x7ED000:
                    found.append(("global", rel, number, value, line.strip(), ok))
    return found, code_refs


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--list", action="store_true")
    args = parser.parse_args()
    names = load_globals()
    found, code_refs = scan()

    per_file = collections.Counter((f[1], f[0]) for f in found if not f[5])
    files = sorted({f for f, _ in per_file})
    addresses = collections.defaultdict(list)
    for kind, rel, number, value, text, ok in found:
        if kind == "global" and not ok:
            addresses[value].append(f"{rel}:{number}")

    lines = []
    lines.append("# Typed access worklist")
    lines.append("")
    lines.append("Generated by `python tools/raw_access_report.py --write`; do not edit by")
    lines.append("hand. Every place in `src/s3re` that still reads game memory through a raw")
    lines.append("offset (`RawAt`) or a raw data address of S3.EXE outside the globals headers.")
    lines.append("Goal: struct fields and typed globals that mirror the real objects.")
    lines.append("")
    n_rawat = sum(1 for f in found if f[0] == "rawat" and not f[5])
    n_global = sum(1 for f in found if f[0] == "global" and not f[5])
    n_ok = sum(1 for f in found if f[5])
    lines.append(f"- RawAt (unmapped object fields): {n_rawat}")
    lines.append(f"- Data addresses outside the globals headers: {n_global} uses of {len(addresses)} addresses")
    lines.append(f"- Marked `raw-ok` (justified): {n_ok}")
    lines.append(f"- Code addresses (calls of original functions, allowed): {code_refs}")
    lines.append("")
    lines.append("## Per file")
    lines.append("")
    lines.append("| file | RawAt | data addresses |")
    lines.append("|---|---|---|")
    for rel in files:
        lines.append(f"| `{rel}` | {per_file[(rel, 'rawat')]} | {per_file[(rel, 'global')]} |")
    lines.append("")
    lines.append("## Data addresses")
    lines.append("")
    lines.append("| address | name in re/globals.csv | used at |")
    lines.append("|---|---|---|")
    for value in sorted(addresses):
        uses = ", ".join(addresses[value][:6]) + (" ..." if len(addresses[value]) > 6 else "")
        lines.append(f"| 0x{value:06x} | {names.get(value, '')} | {uses} |")
    lines.append("")
    lines.append("## RawAt uses")
    lines.append("")
    for kind, rel, number, value, text, ok in found:
        if kind == "rawat" and not ok:
            lines.append(f"- `{rel}:{number}`: `{text[:110]}`")
    lines.append("")
    report = "\n".join(lines)

    if args.list:
        for kind, rel, number, value, text, ok in found:
            tag = " (raw-ok)" if ok else ""
            where = f" 0x{value:06x}" if value else ""
            print(f"{kind}{where} src/s3re/{rel}:{number}{tag}: {text[:120]}")
    else:
        print(f"RawAt {n_rawat}, data-address uses {n_global} ({len(addresses)} addresses, "
              f"{sum(1 for a in addresses if a in names)} named in re/globals.csv), raw-ok {n_ok}, "
              f"code addresses {code_refs}")
        for rel in files:
            print(f"  {rel}: RawAt {per_file[(rel, 'rawat')]}, data {per_file[(rel, 'global')]}")
    if args.write:
        (ROOT / "re" / "typed_access_todo.md").write_text(report, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
