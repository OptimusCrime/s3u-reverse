#!/usr/bin/env python3
"""Regenerate re/ghidra_functions.tsv from an REA evidence bundle.

The bundle must contain a `list_procedures` record for S3.EXE. Produce one
with the REA MCP tools: open_binary(S3.EXE), list_procedures(detail=summary),
then export_evidence_bundle(path=...).

Usage: python tools/import_ghidra_functions.py <bundle.json>

The baseline lists every function start Ghidra found, except external imports
(they are not code in S3.EXE). Unwind@/Catch@ funclets, which are
compiler-generated C++ exception cleanup code rather than functions anybody
wrote, are kept with kind "funclet" so that address-to-function lookups stay
correct, but they are not counted as functions to reverse.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "re" / "ghidra_functions.tsv"
EXPECTED_SHA256 = "00a925cfdcfc3349b5d0f3b8a4c312f01b813e363b4464f6f3d6de17804d950b"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2

    bundle = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
    records = [r for r in bundle["records"] if r.get("operation") == "list_procedures"]
    if not records:
        print("bundle has no list_procedures record", file=sys.stderr)
        return 1
    record = records[-1]
    sha = record["subject"]["digest"]["sha256"]
    if sha != EXPECTED_SHA256:
        print(f"bundle is for a different binary (sha256 {sha})", file=sys.stderr)
        return 1

    rows = []
    funclets = 0
    for proc in record["normalized_result"]:
        if proc["procedure"]["external"]:
            continue
        name = proc["value"]
        if re.match(r"(Unwind|Catch)@", name):
            funclets += 1
            kind = "funclet"
        elif proc["procedure"]["thunk"]:
            kind = "thunk"
        elif proc["symbol"]["source"] == "analysis":
            kind = "library"  # matched by Ghidra's Function ID (CRT and similar)
        else:
            kind = "function"
        rows.append((int(proc["address"], 16), kind, name))
    rows.sort()

    provider = record["provider"]
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as out:
        out.write("# Function starts in S3.EXE found by Ghidra auto-analysis.\n")
        out.write(f"# Generated by tools/import_ghidra_functions.py from {provider['name']} "
                  f"{provider['version']} output.\n")
        out.write(f"# S3.EXE sha256 {EXPECTED_SHA256}\n")
        out.write("# kind: function = unidentified code, library = Function ID match, "
                  "thunk = jump stub,\n")
        out.write("#       funclet = compiler-generated exception cleanup (not counted)\n")
        out.write("address\tkind\tghidra_name\n")
        for address, kind, name in rows:
            out.write(f"0x{address:08x}\t{kind}\t{name}\n")

    print(f"wrote {len(rows) - funclets} functions and {funclets} funclets to "
          f"{OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
